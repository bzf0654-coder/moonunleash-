import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const base = new URL('tests/fixtures/upstream/', root);
const manifest = JSON.parse(await readFile(new URL('manifest.json', base), 'utf8'));
for (const f of manifest.files) {
  const bytes = await readFile(new URL(f.name, base));
  if (createHash('sha256').update(bytes).digest('hex') !== f.sha256) throw Error(`Fixture digest mismatch: ${f.name}`);
}
const index = JSON.parse(await readFile(new URL('index.json', base), 'utf8'));
const mandatory = new Set(['01', '02', '03', '04', '05', '07', '08', '09', '10', '11', '12', '18']);
const inventory = [];
let output = '// Generated by tools/generate-fixtures.mjs. Upstream fixtures are unmodified.\n';
for (const name of index) {
  const source = await readFile(new URL(name, base), 'utf8');
  const spec = JSON.parse(source);
  const id = name.slice(0, 2);
  const status = mandatory.has(id) ? 'Required' : 'NotRun';
  const groups = Object.entries(spec).filter(([k, v]) => /tests$/i.test(k) && Array.isArray(v));
  inventory.push({ file: name, status, groups: Object.fromEntries(groups.map(([k, v]) => [k, v.length])), cases: groups.flatMap(([kind, cases]) => cases.map((c, i) => ({ kind, index: i, description: c.description ?? c.name ?? '', status }))) });
  if (mandatory.has(id)) output += `\n///|\nlet fixture_${id} : String =\n${source.trimEnd().split(/\r?\n/).map(line => '  #|' + line).join('\n')}\n`;
}
await writeFile(new URL('fixtures_generated_test.mbt', root), output);
await writeFile(new URL('docs/spec-inventory.json', root), JSON.stringify({ revision: manifest.revision, suites: inventory }, null, 2) + '\n');
console.log(`Verified ${manifest.files.length} hashes; generated ${mandatory.size} fixture bindings and full ${index.length}-suite inventory.`);
